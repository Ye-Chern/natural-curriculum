"""Research integrity checks: incomplete evidence must never look like a completed scan."""
import copy
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]


def module(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / f"scripts/{name}.py")
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


runner = module("minimal_index")
sync = module("sync_content")


class ResearchTests(unittest.TestCase):
    def setUp(self):
        # Independently hand-constructed degree-2 run, not generated by GAP.
        self.rows = [dict(type="meta", gap="test", primgrp="test", bound=2),
                     dict(type="simple", degree=2, id=1, order=2, label="C2", first=[2, 1],
                          new=True, stabilizer_order=1, generators=[[2, 1]]),
                     dict(type="degree", degree=2, primitive_count=1, simple_actions=1, new_classes=1),
                     dict(type="done", classes=1, isomorphism_calls=0)]

    def summarize(self, rows):
        return runner.summarize("\n".join(json.dumps(r) for r in rows), 2)

    def test_minimal_valid_run(self):
        self.assertEqual(self.summarize(self.rows)["classes"][0]["mu"], 2)

    def test_reject_incomplete_run(self):
        with self.assertRaises(ValueError):
            self.summarize(self.rows[:-1])

    def test_reject_missing_stage(self):
        with self.assertRaises(ValueError):
            self.summarize(self.rows[:2] + self.rows[3:])

    def test_reject_dangling_isomorphism_reference(self):
        rows = copy.deepcopy(self.rows)
        rows[1].update(new=False, first=[2, 9])
        with self.assertRaises(ValueError):
            self.summarize(rows)

    def test_reject_bad_generator(self):
        rows = copy.deepcopy(self.rows)
        rows[1]["generators"] = [[1, 1]]
        with self.assertRaises(ValueError):
            self.summarize(rows)

    def test_reject_non_boolean_new_flag(self):
        rows = copy.deepcopy(self.rows)
        rows[1]["new"] = "true"
        with self.assertRaises(ValueError):
            self.summarize(rows)

    def test_frozen_scan_and_independent_mathematical_anchors(self):
        path = ROOT / "research/results/minimal-index-12.jsonl"
        summary = runner.summarize(path.read_text(encoding="utf-8"), 12)
        small = sorted((r["mu"], r["order"]) for r in summary["classes"] if r["mu"] <= 7)
        # Theoretical classification; orders uniquely distinguish THESE eight groups only.
        self.assertEqual(small, [(2, 2), (3, 3), (5, 5), (5, 60), (6, 360), (7, 7), (7, 168), (7, 2520)])
        a5 = next(r for r in summary["classes"] if r["order"] == 60)
        self.assertTrue(any(n == 6 for n, _ in a5["actions"]))

    def test_research_does_not_enter_textbook_navigation(self):
        outputs = sync.outputs()
        nav = outputs[ROOT / "_chapters.yml"]
        self.assertNotIn("minimal-index", nav)
        self.assertFalse(any(line.lstrip().startswith("- research/") for line in nav.splitlines()))

    def test_unreviewed_research_cannot_create_chapter(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "research").mkdir()
            note = root / "research/note.md"
            note.write_text("An unreviewed calculation.", encoding="utf-8")
            event = dict(id="candidate", kind="research", parameter="n=12", object="test",
                         evidence="a calculation", dependencies="GAP", status="computed",
                         research_file="research/note.md")
            path = root / "research/events.json"
            path.write_text(json.dumps([event]), encoding="utf-8")
            with patch.object(sync, "ROOT", root):
                self.assertNotIn("note.md", sync.outputs()[root / "_chapters.yml"])
                event["status"] = "proved"
                path.write_text(json.dumps([event]), encoding="utf-8")
                with self.assertRaisesRegex(ValueError, "chapter"):
                    sync.outputs()


if __name__ == "__main__":
    unittest.main()
