"""Generate navigation and event index from completed, evidenced content only."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    events = json.loads((ROOT / "research/events.json").read_text(encoding="utf-8"))
    chapters, seen = [], set()
    lines = ["---", "number-sections: false", "---", "", "# 已经发生的数学事件 {.unnumbered}", "",
             "这里记录本书已经解释并证明的结构变化与工具。每项单独说明对象、参数与适用范围；钟面格数、作用次数与最小子群指数分别标记。", "",
             "这是内容索引，不是预定课程表。元数据见仓库 `research/events.json`；只有状态为 `proved` 的条目进入此页与正文导航。", ""]
    for event in events:
        for key in ["id", "kind", "parameter", "object", "evidence", "status", "dependencies"]:
            if not event.get(key):
                raise ValueError(f"Event missing {key}: {event}")
        if event["id"] in seen:
            raise ValueError("Duplicate event id")
        seen.add(event["id"])
        if event["status"] != "proved":
            research_file = event.get("research_file")
            if not research_file or not (ROOT / research_file).is_file():
                raise ValueError(f"Missing research file: {event['id']}")
            continue
        if not event.get("chapter") or not event.get("anchor"):
            raise ValueError(f"Missing chapter/anchor: {event['id']}")
        chapter = ROOT / event["chapter"]
        if not chapter.is_file() or not re.search(r"\{[^}]*#" + re.escape(event["anchor"]) + r"[\s}]", chapter.read_text(encoding="utf-8")):
            raise ValueError(f"Missing chapter/anchor: {event['id']}")
        if event["chapter"] not in chapters:
            chapters.append(event["chapter"])
        lines += [f"## {event['object']}", "", f"**类别**：{event['kind']}。**参数**：{event['parameter']}。", "",
                  f"**首次出现或适用范围的证据**：{event['evidence']}", "",
                  f"**状态**：正文证明完成。**依赖**：{event['dependencies']}。", "",
                  f"[阅读证明]({event['chapter']}#{event['anchor']})", ""]
    nav = "# Generated by scripts/sync_content.py; edit research/events.json instead.\nbook:\n  chapters:\n"
    nav += "".join(f"    - {p}\n" for p in ["index.qmd", *chapters, "events.qmd", "references.qmd"])
    return {ROOT / "_chapters.yml": nav, ROOT / "events.qmd": "\n".join(lines)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated content: {path.name}; run python scripts/sync_content.py")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    print("Content navigation and event index are current.")
